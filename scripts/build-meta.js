// Writes public/js/node-meta.js from src/nodes.js so the browser editor
// (and the web edition) know every node's fields. Run: npm run build:meta
const fs = require("node:fs");
const path = require("node:path");
const { publicNodeList } = require("../src/nodes");
const out = path.join(__dirname, "..", "public", "js", "node-meta.js");
const body = `/* generated by scripts/build-meta.js — do not edit by hand */\nwindow.YF_NODE_META = ${JSON.stringify(publicNodeList(), null, 1)};\n`;
fs.writeFileSync(out, body);
console.log("wrote", path.relative(process.cwd(), out));
